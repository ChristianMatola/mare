    setor text NOT NULL DEFAULT '',
    nome_evento text NOT NULL DEFAULT '',
    deao_artista text NOT NULL DEFAULT '',
    razao_social text NOT NULL DEFAULT '',
    cnpj text NOT NULL DEFAULT '',
    nota_fiscal text NOT NULL DEFAULT '',
    data_emissao_nf text NOT NULL DEFAULT '',
    valor text NOT NULL DEFAULT '',
    valor_extenso text NOT NULL DEFAULT '',
    volumes text NOT NULL DEFAULT '',
    num_contrato text NOT NULL DEFAULT '',
    data_ass_contrato text NOT NULL DEFAULT '',
    pgs_copia_contrato text NOT NULL DEFAULT '',
    num_paginas text NOT NULL DEFAULT '',
    num_processo_contratacao text NOT NULL DEFAULT '',
    num_ordem_servico text NOT NULL DEFAULT '',
    data_relato text NOT NULL DEFAULT '',
    num_empenho text NOT NULL DEFAULT '',
    folhas_empenho text NOT NULL DEFAULT '',
    folhas_termo_referencia text NOT NULL DEFAULT '',
    folha_memoria_calculo text NOT NULL DEFAULT '',
    folha_autorizo text NOT NULL DEFAULT '',
    folhas_extrato_contrato text NOT NULL DEFAULT '',
    folhas_nota_fiscal text NOT NULL DEFAULT '',
