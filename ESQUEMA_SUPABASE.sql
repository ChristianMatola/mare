    cert_trabalhista_validade text NOT NULL DEFAULT '',
    cert_trabalhista_folha text NOT NULL DEFAULT '',
    cert_federal_emissao text NOT NULL DEFAULT '',
    cert_federal_validade text NOT NULL DEFAULT '',
    cert_federal_folha text NOT NULL DEFAULT '',
    cert_fgts_emissao text NOT NULL DEFAULT '',
    cert_fgts_validade text NOT NULL DEFAULT '',
    cert_fgts_folha text NOT NULL DEFAULT '',
