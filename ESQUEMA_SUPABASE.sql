CREATE TABLE IF NOT EXISTS mare.apontamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    processo_id bigint NOT NULL REFERENCES mare.processos(id),
    sequencia text NOT NULL,
    pagina text NOT NULL,
    apontamento text NOT NULL,
    status text NOT NULL,
    criado_em text NOT NULL,
    atualizado_em text NOT NULL
);

CREATE TABLE IF NOT EXISTS mare.status_apontamentos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome text NOT NULL UNIQUE,
    criado_em text NOT NULL
);

CREATE TABLE IF NOT EXISTS mare.modelos (
    tipo_processo text PRIMARY KEY,
    conteudo bytea NOT NULL
);

CREATE INDEX IF NOT EXISTS apontamentos_processo_idx ON mare.apontamentos (processo_id);
