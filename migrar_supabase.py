"""Importa uma cópia consistente do SQLite para um esquema MARÉ vazio."""

import os
import sqlite3
from getpass import getpass

import psycopg
from psycopg import sql

from app import ALL_KEYS, DB_PATH, STATUS_APONTAMENTO_PADRAO, TEMPLATE_PATH


def main():
    database_url = os.environ.get("MARE_DATABASE_ADMIN_URL")
    if not database_url:
        raise SystemExit("Defina MARE_DATABASE_ADMIN_URL antes de executar a migração.")
    password = os.environ.get("MARE_DATABASE_APP_PASSWORD") or getpass("Senha nova para mare_aplicacao: ")
    if len(password) < 24:
        raise SystemExit("Use uma senha exclusiva de pelo menos 24 caracteres para mare_aplicacao.")
    template = TEMPLATE_PATH.read_bytes()

    source = sqlite3.connect(DB_PATH.as_uri() + "?mode=ro", uri=True)
    snapshot = sqlite3.connect(":memory:")
    try:
        source.backup(snapshot)
    finally:
        source.close()
    snapshot.row_factory = sqlite3.Row
    if snapshot.execute("PRAGMA integrity_check").fetchone()[0] != "ok":
        raise SystemExit("O SQLite não passou na verificação de integridade.")

    with psycopg.connect(database_url, prepare_threshold=None, sslmode="require",
                         connect_timeout=10) as conn:
        conn.execute("SELECT pg_advisory_xact_lock(42780310)")
        conn.execute("CREATE SCHEMA IF NOT EXISTS mare")
        conn.execute("REVOKE ALL ON SCHEMA mare FROM PUBLIC")
        conn.execute("SET LOCAL search_path TO mare")
        columns = sql.SQL(", ").join(
            sql.SQL("{} text NOT NULL DEFAULT ''").format(sql.Identifier(key))
            for key in [*ALL_KEYS, "observacoes"]
        )
        conn.execute(sql.SQL("""
            CREATE TABLE IF NOT EXISTS processos (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                {},
                status text NOT NULL DEFAULT 'RASCUNHO',
                criado_em text NOT NULL,
                atualizado_em text NOT NULL,
                arquivo_gerado text NOT NULL DEFAULT ''
            )
        """).format(columns))
        conn.execute("""
            CREATE TABLE IF NOT EXISTS apontamentos (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                processo_id bigint NOT NULL REFERENCES processos(id),
                sequencia text NOT NULL,
                pagina text NOT NULL,
                apontamento text NOT NULL,
                status text NOT NULL,
                criado_em text NOT NULL,
                atualizado_em text NOT NULL
            )
        """)
        conn.execute("""
            CREATE TABLE IF NOT EXISTS status_apontamentos (
                id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nome text NOT NULL UNIQUE,
                criado_em text NOT NULL
            )
        """)
        conn.execute("CREATE INDEX IF NOT EXISTS apontamentos_processo_idx ON apontamentos (processo_id)")
        conn.execute("""
            CREATE TABLE IF NOT EXISTS modelos (
                tipo_processo text PRIMARY KEY,
                conteudo bytea NOT NULL
            )
        """)
        conn.execute("LOCK TABLE processos, apontamentos, status_apontamentos IN EXCLUSIVE MODE")
        tables = {
            "processos": ["id", *ALL_KEYS, "observacoes", "status", "criado_em", "atualizado_em", "arquivo_gerado"],
            "apontamentos": ["id", "processo_id", "sequencia", "pagina", "apontamento", "status", "criado_em", "atualizado_em"],
            "status_apontamentos": ["id", "nome", "criado_em"],
        }
        counts = {}
        for table, allowed in tables.items():
            name = sql.Identifier(table)
            if conn.execute(sql.SQL("SELECT EXISTS (SELECT 1 FROM {})").format(name)).fetchone()[0]:
                raise SystemExit("O destino contém dados. A importação foi cancelada.")
            source_columns = {row["name"] for row in snapshot.execute(f"PRAGMA table_info({table})")}
            fields = [field for field in allowed if field in source_columns]
            if not fields:
                counts[table] = 0
                continue
            rows = snapshot.execute(f"SELECT {', '.join(fields)} FROM {table}").fetchall()
            insert = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                name, sql.SQL(", ").join(map(sql.Identifier, fields)),
                sql.SQL(", ").join(sql.Placeholder() for _ in fields)
            )
            for row in rows:
                conn.execute(insert, tuple(row))
            next_id = max((row["id"] for row in rows), default=0) + 1
            conn.execute(sql.SQL("ALTER TABLE {} ALTER COLUMN id RESTART WITH {}").format(
                name, sql.Literal(next_id)))
            counts[table] = len(rows)
        for status in STATUS_APONTAMENTO_PADRAO:
            conn.execute("""
                INSERT INTO status_apontamentos (nome, criado_em)
                VALUES (%s, CURRENT_TIMESTAMP::text) ON CONFLICT (nome) DO NOTHING
            """, (status,))
        conn.execute("INSERT INTO modelos (tipo_processo, conteudo) VALUES (%s, %s)", ("pagamento", template))
        verifier = conn.pgconn.encrypt_password(password.encode(), b"mare_aplicacao", b"scram-sha-256")
        conn.execute(sql.SQL("""
            CREATE ROLE mare_aplicacao LOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE
            NOREPLICATION NOBYPASSRLS PASSWORD {}
        """).format(sql.Literal(verifier.decode("ascii"))))
        conn.execute("GRANT USAGE ON SCHEMA mare TO mare_aplicacao")
        conn.execute("GRANT USAGE ON ALL SEQUENCES IN SCHEMA mare TO mare_aplicacao")
        privileges = {
            "processos": "SELECT, INSERT, UPDATE",
            "apontamentos": "SELECT, INSERT, UPDATE, DELETE",
            "status_apontamentos": "SELECT, INSERT",
            "modelos": "SELECT",
        }
        for table, grants in privileges.items():
            name = sql.Identifier(table)
            conn.execute(sql.SQL("REVOKE ALL ON {} FROM PUBLIC").format(name))
            conn.execute(sql.SQL("ALTER TABLE {} ENABLE ROW LEVEL SECURITY").format(name))
            conn.execute(sql.SQL("ALTER TABLE {} FORCE ROW LEVEL SECURITY").format(name))
            conn.execute(sql.SQL("GRANT {} ON {} TO mare_aplicacao").format(sql.SQL(grants), name))
            conn.execute(sql.SQL("""
                CREATE POLICY acesso_equipe_mare ON {} TO mare_aplicacao
                USING (true) WITH CHECK (true)
            """).format(name))
    snapshot.close()
    for table, count in counts.items():
        print(f"{table}: {count} registro(s) importado(s)")


if __name__ == "__main__":
    main()
